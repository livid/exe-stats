TOUCH, TOUCH_SCALE = 180, 5
TOUCH_AT = (13, 8)  # the 32's top left: its body a little under the middle, its button above


def art(n):
    rows = ICONS[n].split()
    assert len(rows) == n and all(len(r) == n for r in rows), n
    im = Image.new('RGBA', (n, n), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c != '.':
                im.putpixel((x, y), PAL[c] + (255,))
    return im


def ico(images):
    """An .ico of PNG frames, which every browser of the last decade reads."""
    pngs = []
    for im in images:
        b = io.BytesIO()
        im.save(b, 'PNG', optimize=True)
        pngs.append(b.getvalue())
    out = struct.pack('<HHH', 0, 1, len(images))
    offset = 6 + 16 * len(images)
    for im, png in zip(images, pngs):
        out += struct.pack('<BBBBHHII', im.width % 256, im.height % 256, 0, 0, 1, 32, len(png), offset)
        offset += len(png)
    return out + b''.join(pngs)


def touch():
    im = Image.new('RGB', (TOUCH, TOUCH), LAVENDER)
    big = art(32).resize((32 * TOUCH_SCALE, 32 * TOUCH_SCALE), Image.NEAREST)
    im.paste(big, (TOUCH_AT[0], TOUCH_AT[1]), big)
    return im


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    sizes = sorted(ICONS)
    with open(os.path.join(here, 'favicon.ico'), 'wb') as f:
        f.write(ico([art(n) for n in sizes]))
    touch().save(os.path.join(here, 'apple-touch-icon.png'), optimize=True)
    if len(sys.argv) > 1:
        scale, gap = 8, 16
        w = sum(n * scale + gap for n in sizes) + TOUCH + gap
        sheet = Image.new('RGB', (w, 32 * scale + 2 * gap), (0x55, 0x55, 0x55))
        x = gap
        for n in sizes:
            big = art(n).resize((n * scale, n * scale), Image.NEAREST)
            sheet.paste(big, (x, gap), big)
            x += n * scale + gap
        sheet.paste(touch(), (x, gap))
        sheet.save(sys.argv[1])
    for name in ('favicon.ico', 'apple-touch-icon.png'):
        print(f"{name}: {os.path.getsize(os.path.join(here, name))} bytes")


if __name__ == '__main__':
    main()
